// Currency formatting
export const inr = (n) =>
  "₹" + Math.round(n).toLocaleString("en-IN");

export const lakhs = (n) =>
  "₹" + (n / 100000).toFixed(2) + " L";

// Generate dummy plots for each venture
export function createPlots(v) {
  const arr = [];
  const rows = 9;
  const cols = 12;

  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const id = r * cols + c + 1;

      const size =
        v.min +
        ((r * 29 + c * 17) %
          Math.max(1, v.max - v.min));

      const status =
        id <= Math.round((v.open / v.plots) * 108)
          ? "available"
          : id % 7 === 0
          ? "reserved"
          : "sold";

      arr.push({
        id,
        size,
        status,
        facing: ["East", "West", "North", "South"][
          (r + c) % 4
        ],
        r,
        c,
      });
    }
  }

  return arr;
}
